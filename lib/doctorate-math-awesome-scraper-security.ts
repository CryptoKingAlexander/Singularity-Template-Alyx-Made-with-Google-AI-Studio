export type PivotDimensionKey = 'category' | 'format' | 'authTier' | 'cadence';

export interface PivotCellSummary {
  rowKey: string;
  colKey: string;
  count: number;
  meanScore: number;
  sampleIds: string[];
}

export function buildAwesomeDataPivotMatrix(
  sources: AwesomeFreeDataSource[],
  rowDim: PivotDimensionKey,
  colDim: PivotDimensionKey
): {
  rowKeys: string[];
  colKeys: string[];
  cells: Record<string, PivotCellSummary>;
  rowTotals: Record<string, number>;
  colTotals: Record<string, number>;
} {
  const rowSet = new Set<string>();
  const colSet = new Set<string>();
  const cells: Record<string, PivotCellSummary> = {};
  const rowTotals: Record<string, number> = {};
  const colTotals: Record<string, number> = {};

  for (const src of sources) {
    const r = String(src[rowDim]);
    const c = String(src[colDim]);
    rowSet.add(r);
    colSet.add(c);
    const key = `${r}|||${c}`;
    if (!cells[key]) {
      cells[key] = {
        rowKey: r,
        colKey: c,
        count: 0,
        meanScore: 0,
        sampleIds: [],
      };
    }
    const cell = cells[key];
    const totalScore = cell.meanScore * cell.count + src.pivotWeightScore;
    cell.count += 1;
    cell.meanScore = Number((totalScore / cell.count).toFixed(2));
    if (cell.sampleIds.length < 3) {
      cell.sampleIds.push(src.id);
    }
    rowTotals[r] = (rowTotals[r] || 0) + 1;
    colTotals[c] = (colTotals[c] || 0) + 1;
  }

  return {
    rowKeys: Array.from(rowSet),
    colKeys: Array.from(colSet),
    cells,
    rowTotals,
    colTotals,
  };
}

